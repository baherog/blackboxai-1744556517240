let currentLanguage = 'en';

function changeLanguage(lang) {
    currentLanguage = lang;
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
    
    // Update text direction for Arabic
    if (lang === 'ar') {
        document.documentElement.dir = 'rtl';
    } else {
        document.documentElement.dir = 'ltr';
    }
    
    // Update all content
    const elements = {
        'page-title': 'pageTitle',
        'header-title': 'headerTitle',
        'nav-services': 'navServices',
        'nav-about': 'navAbout',
        'nav-contact': 'navContact',
        'hero-title': 'heroTitle',
        'hero-subtitle': 'heroSubtitle',
        'services-heading': 'servicesHeading',
        'service1-title': 'service1Title',
        'service1-desc': 'service1Desc',
        'service2-title': 'service2Title',
        'service2-desc': 'service2Desc',
        'service3-title': 'service3Title',
        'service3-desc': 'service3Desc',
        'services-description': 'servicesDescription',
        'about-heading': 'aboutHeading',
        'about-description': 'aboutDescription',
        'contact-heading': 'contactHeading',
        'contact-email': 'contactEmail',
        'features-heading': 'featuresHeading',
        'feature1-title': 'feature1Title',
        'feature1-desc': 'feature1Desc',
        'feature2-title': 'feature2Title',
        'feature2-desc': 'feature2Desc',
        'feature3-title': 'feature3Title',
        'feature3-desc': 'feature3Desc',
        'feature4-title': 'feature4Title',
        'feature4-desc': 'feature4Desc',
        'footer-text': 'footerText'
    };
    
    // Update each element
    Object.keys(elements).forEach(elementId => {
        const element = document.getElementById(elementId);
        const contentKey = elements[elementId];
        if (element && content[currentLanguage][contentKey]) {
            element.textContent = content[currentLanguage][contentKey];
        }
    });
    
    // Update language button states
    document.getElementById('langEn').classList.toggle('active', lang === 'en');
    document.getElementById('langAr').classList.toggle('active', lang === 'ar');
    
    // Save language preference
    localStorage.setItem('preferredLanguage', lang);
    
    console.log(`Language changed to: ${lang}`);
}

// Load saved language preference on page load
document.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('preferredLanguage');
    if (savedLang) {
        changeLanguage(savedLang);
    }
});
